def _fingerprint_checkpoint(path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _checkpoint_signature() -> tuple[str, int, int]:
    if not ACTIVE_CHECKPOINT_PATH.is_file():
        raise HTTPException(status_code=503, detail="No active model checkpoint is configured")
    stat = ACTIVE_CHECKPOINT_PATH.stat()
    return str(ACTIVE_CHECKPOINT_PATH.resolve()), stat.st_mtime_ns, stat.st_size


def _active_model_fingerprint() -> str:
    signature = _checkpoint_signature()
    if getattr(app.state, "checkpoint_signature", None) != signature:
        app.state.checkpoint_fingerprint = _fingerprint_checkpoint(ACTIVE_CHECKPOINT_PATH)
        app.state.checkpoint_signature = signature
        app.state.model = None
    return app.state.checkpoint_fingerprint


def _normalized_embedding(values: list[float]) -> list[float]:
    vector = np.asarray(values, dtype=np.float64)
    if vector.shape != (512,) or not np.isfinite(vector).all():
        raise HTTPException(status_code=422, detail="Embedding must contain 512 finite values")
    magnitude = float(np.linalg.norm(vector))
    if not np.isfinite(magnitude) or magnitude <= 1e-12:
        raise HTTPException(status_code=422, detail="Embedding must have nonzero finite magnitude")
    return (vector / magnitude).astype(np.float32).tolist()


def _require_active_model(payload: "EmbeddingPayload") -> str:
    active_fingerprint = _active_model_fingerprint()
    if payload.model_fingerprint != active_fingerprint:
        raise HTTPException(
            status_code=409,
            detail="Embedding was generated by a different model checkpoint; extract it again with the active model.",
        )
    return active_fingerprint


@asynccontextmanager
async def lifespan(_: FastAPI):
    active_fingerprint = None
    # Only tag pre-migration gallery rows when the legacy deployed checkpoint is active.
    if ACTIVE_CHECKPOINT_PATH.resolve() == DEPLOYED_CHECKPOINT_PATH.resolve() and ACTIVE_CHECKPOINT_PATH.is_file():
        active_fingerprint = _fingerprint_checkpoint(ACTIVE_CHECKPOINT_PATH)
    initialize_database(legacy_model_fingerprint=active_fingerprint)
    if active_fingerprint:
        app.state.checkpoint_fingerprint = active_fingerprint
        app.state.checkpoint_signature = _checkpoint_signature()
    yield


