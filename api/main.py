@app.middleware("http")
async def reject_oversized_image_requests(request, call_next):
    if request.url.path == "/api/recognition/embedding" and request.method == "POST":
        content_length = request.headers.get("content-length")
        if content_length:
            try:
                request_size = int(content_length)
            except ValueError:
                return JSONResponse(status_code=400, content={"detail": "Invalid Content-Length header"})
            if request_size > MAX_UPLOAD_BYTES + 256 * 1024:
                return JSONResponse(status_code=413, content={"detail": "Image upload exceeds the 10 MiB limit"})
    return await call_next(request)


class EmbeddingPayload(BaseModel):
    embedding: list[float] = Field(min_length=512, max_length=512)
    model_fingerprint: Optional[str] = Field(default=None, min_length=64, max_length=64)

    @field_validator("embedding")
    @classmethod
    def embedding_values_must_be_finite(cls, values: list[float]) -> list[float]:
        if not np.isfinite(np.asarray(values, dtype=np.float64)).all():
            raise ValueError("Embedding values must be finite")
        return values


def _similarity(left: list[float], right: list[float]) -> float:
    a, b = np.asarray(left, dtype=np.float64), np.asarray(right, dtype=np.float64)
    if not np.isfinite(a).all() or not np.isfinite(b).all():
        return 0.0
    denom = float(np.linalg.norm(a) * np.linalg.norm(b))
    return float(np.clip(np.dot(a, b) / denom, -1.0, 1.0)) if np.isfinite(denom) and denom else 0.0


def _run_local_job(job_id: str, target_far: Optional[float]) -> None:
    with SessionLocal() as session:
        job = session.get(AnalysisJob, job_id)
        if job is None:
            return
        job.status = "running"
        session.commit()
        try:
            job.result = optimize_threshold(target_far=target_far)
            job.status = "completed"
        except Exception:
            logger.exception("Threshold optimization failed for job %s", job_id)
            job.error = "Threshold optimization failed; check the local API logs."
            job.status = "failed"
        session.commit()


