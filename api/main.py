@app.get("/api/dashboard")
def dashboard() -> dict[str, Any]:
    active_fingerprint = None
    if ACTIVE_CHECKPOINT_PATH.is_file():
        active_fingerprint = _active_model_fingerprint()
    with SessionLocal() as session:
        total_identities = session.scalar(select(func.count()).select_from(Identity)) or 0
        identities = 0
        if active_fingerprint:
            identities = session.scalar(
                select(func.count()).select_from(Identity).where(
                    Identity.model_fingerprint == active_fingerprint
                )
            ) or 0
    stats = load_reference_stats()
    genuine = stats.get("intra_class_similarity", {})
    impostor = stats.get("inter_class_similarity", {})
    evaluation = {}
    report_matches_checkpoint = checkpoint_matches_evaluation()
    if report_matches_checkpoint:
        with REPORT_PATH.open(encoding="utf-8") as source:
            evaluation = json.load(source)
        if ACTIVE_CHECKPOINT_PATH.resolve() == RUN_CHECKPOINT_PATH.resolve():
            genuine = evaluation.get("genuine_stats", genuine)
            impostor = evaluation.get("impostor_stats", impostor)
    return {
        "identity_count": identities,
        "stale_identity_count": total_identities - identities,
        "model_available": ACTIVE_CHECKPOINT_PATH.is_file(),
        "active_checkpoint": ACTIVE_CHECKPOINT_PATH.name,
        "candidate_model_available": RUN_CHECKPOINT_PATH.is_file(),
        "candidate_model_active": ACTIVE_CHECKPOINT_PATH.resolve() == RUN_CHECKPOINT_PATH.resolve(),
        "candidate_run_name": RUN_NAME,
        "candidate_validation_eer": evaluation.get("checkpoint_validation_eer"),
        "dataset_reference": {
            "classes": stats.get("total_classes", 0),
            "embeddings": stats.get("total_embeddings", 0),
            "embedding_dimension": stats.get("embedding_dim", 512),
            "genuine_mean": genuine.get("mean"),
            "impostor_mean": impostor.get("mean"),
        },
        "stats_are_reference": not bool(evaluation) or (
            ACTIVE_CHECKPOINT_PATH.resolve() != RUN_CHECKPOINT_PATH.resolve()
        ),
        "empirical_evaluation_available": report_matches_checkpoint and SCORES_PATH.is_file(),
        "evaluation_split": evaluation.get("split"),
        "heldout_evaluation": {
            "available": bool(evaluation.get("test_at_validation_eer")),
            "calibration_split": evaluation.get("calibration_split"),
            "test_split": evaluation.get("split"),
            "test_roc_auc": evaluation.get("test_roc_auc"),
            "test_at_validation_eer": evaluation.get("test_at_validation_eer"),
            "test_at_fixed_threshold": evaluation.get("test_at_fixed_threshold"),
            "target_far_operations": evaluation.get("target_far_operations", {}),
            "num_genuine_pairs": evaluation.get("num_genuine_pairs"),
            "num_impostor_pairs": evaluation.get("num_impostor_pairs"),
            "subject_cluster_bootstrap": evaluation.get("subject_cluster_bootstrap"),
        },
    }


@app.get("/api/identities")
def list_identities() -> list[dict[str, Any]]:
    if not ACTIVE_CHECKPOINT_PATH.is_file():
        return []
    active_fingerprint = _active_model_fingerprint()
    with SessionLocal() as session:
        rows = session.scalars(
            select(Identity).where(Identity.model_fingerprint == active_fingerprint)
            .order_by(Identity.created_at.desc()).limit(100)
        ).all()
        return [
            {"user_id": row.user_id, "eye": row.eye, "person_id": row.person_id,
             "num_samples": row.num_samples, "created_at": row.created_at.isoformat()}
            for row in rows
        ]


@app.post("/api/identities/{user_id}", status_code=201)
def register_identity(
    user_id: Annotated[str, APIPath(min_length=1, max_length=120)],
    payload: EmbeddingPayload,
    eye: str = Query(default="", pattern="^(|L|R)$"),
    person_id: str = Query(default="", max_length=120),
) -> dict[str, Any]:
    fingerprint = _require_active_model(payload)
    vector = _normalized_embedding(payload.embedding)
    with SessionLocal() as session:
        existing = session.get(Identity, user_id)
        if existing and existing.model_fingerprint == fingerprint:
            raise HTTPException(status_code=409, detail="Identity is already registered")
        if existing:
            existing.eye = eye.upper()
            existing.person_id = person_id
            existing.embedding = vector
            existing.model_fingerprint = fingerprint
            existing.num_samples = 1
            existing.created_at = datetime.now(timezone.utc)
            status = "re-enrolled"
        else:
            session.add(Identity(
                user_id=user_id, eye=eye.upper(), person_id=person_id,
                embedding=vector, model_fingerprint=fingerprint,
            ))
            status = "registered"
        session.commit()
    return {"user_id": user_id, "status": status}


@app.delete("/api/identities/{user_id}", status_code=204)
def delete_identity(user_id: Annotated[str, APIPath(min_length=1, max_length=120)]) -> None:
    with SessionLocal() as session:
        row = session.get(Identity, user_id)
        if row is None:
            raise HTTPException(status_code=404, detail="Identity not found")
        session.delete(row)
        session.commit()


@app.post("/api/identify")
def identify(
    payload: EmbeddingPayload,
    threshold: float = Query(default=0.75, ge=-1.0, le=1.0),
) -> dict[str, Any]:
    fingerprint = _require_active_model(payload)
    query = _normalized_embedding(payload.embedding)
    with SessionLocal() as session:
        rows = session.scalars(
            select(Identity).where(Identity.model_fingerprint == fingerprint)
        ).all()
    if not rows:
        raise HTTPException(status_code=404, detail="No identities are enrolled with the active model")
    best = max(rows, key=lambda row: _similarity(query, row.embedding))
    score = _similarity(query, best.embedding)
    return {"user_id": best.user_id if score >= threshold else None,
            "similarity": score, "threshold": threshold, "matched": score >= threshold}


@app.post("/api/verify/{user_id}")
def verify_identity(
    user_id: Annotated[str, APIPath(min_length=1, max_length=120)],
    payload: EmbeddingPayload,
    threshold: float = Query(default=0.75, ge=-1.0, le=1.0),
) -> dict[str, Any]:
    fingerprint = _require_active_model(payload)
    query = _normalized_embedding(payload.embedding)
    with SessionLocal() as session:
        identity = session.get(Identity, user_id)
        if identity is None:
            raise HTTPException(status_code=404, detail="Identity not found in the gallery")
        if identity.model_fingerprint != fingerprint:
            raise HTTPException(
                status_code=409,
                detail="Identity was enrolled with another model; re-enroll it with the active model.",
            )
        score = _similarity(query, identity.embedding)
    return {"user_id": user_id, "similarity": score, "threshold": threshold, "verified": score >= threshold}


@app.post("/api/analytics/optimize", status_code=202)
def create_optimization_job(
    background_tasks: BackgroundTasks,
    target_far: Optional[float] = Query(default=None, ge=0.0, le=1.0),
) -> dict[str, str]:
    job_id = str(uuid.uuid4())
    with SessionLocal() as session:
        session.add(AnalysisJob(id=job_id, status="queued"))
        session.commit()
    background_tasks.add_task(_run_local_job, job_id, target_far)
    return {"job_id": job_id, "status": "queued"}


