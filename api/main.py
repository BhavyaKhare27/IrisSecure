@app.post("/api/recognition/embedding", include_in_schema=False)
async def extract_embedding(image: UploadFile = File(...)) -> dict[str, Any]:
    """Extract an in-memory embedding from a bounded, validated image upload."""
    import cv2
    from io import BytesIO
    from PIL import Image, UnidentifiedImageError
    import torch
    from torchvision import transforms
    from models.feature_extractor import IrisEmbeddingNet
    from utils.preprocessing import apply_clahe

    try:
        raw = await image.read(MAX_UPLOAD_BYTES + 1)
    finally:
        await image.close()
    if len(raw) > MAX_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail="Image upload exceeds the 10 MiB limit")
    if not raw:
        raise HTTPException(status_code=422, detail="Image upload is empty")
    try:
        with Image.open(BytesIO(raw)) as source:
            if source.format not in {"JPEG", "PNG", "WEBP", "BMP"}:
                raise HTTPException(status_code=415, detail="Upload a JPEG, PNG, WebP, or BMP image")
            width, height = source.size
            if (width > MAX_IMAGE_SIDE or height > MAX_IMAGE_SIDE
                    or width * height > MAX_IMAGE_PIXELS):
                raise HTTPException(status_code=413, detail="Image dimensions exceed the 25-megapixel limit")
            source.verify()
        with Image.open(BytesIO(raw)) as source:
            frame = np.asarray(source.convert("L"), dtype=np.uint8)
    except HTTPException:
        raise
    except (UnidentifiedImageError, OSError, ValueError, Image.DecompressionBombError) as exc:
        raise HTTPException(status_code=422, detail="Uploaded file is not a valid supported image") from exc

    fingerprint = _active_model_fingerprint()
    signature = _checkpoint_signature()
    if torch.cuda.is_available():
        device = torch.device("cuda")
    elif hasattr(torch.backends, "mps") and torch.backends.mps.is_available():
        device = torch.device("mps")
    else:
        device = torch.device("cpu")
    model = getattr(app.state, "model", None)
    if model is None or getattr(app.state, "model_signature", None) != signature:
        try:
            checkpoint_data = torch.load(
                ACTIVE_CHECKPOINT_PATH, map_location=device, weights_only=True
            )
        except Exception as exc:
            logger.exception("Could not safely load the active model checkpoint")
            raise HTTPException(status_code=503, detail="The active model checkpoint could not be loaded safely") from exc
        model_config = checkpoint_data.get("config", {}).get("model", {})
        backbone = model_config.get("backbone", "resnet50")
        embedding_dim = model_config.get("embedding_dim", 512)
        if backbone not in {"resnet18", "resnet50", "mobilenet_v2"} or embedding_dim != 512:
            raise HTTPException(status_code=503, detail="The active checkpoint has an unsupported model configuration")
        try:
            model = IrisEmbeddingNet(
                backbone=backbone, embedding_dim=embedding_dim, pretrained=False
            )
            model.load_state_dict(checkpoint_data["model_state_dict"], strict=True)
        except Exception as exc:
            logger.exception("Active model weights do not match the configured architecture")
            raise HTTPException(status_code=503, detail="The active model weights do not match the model configuration") from exc
        app.state.model = model.to(device).eval()
        app.state.model_signature = signature
        app.state.model_fingerprint = fingerprint

    frame = cv2.GaussianBlur(frame, (3, 3), 0)
    frame = apply_clahe(frame)
    frame = cv2.resize(frame, (224, 224))
    rgb = np.stack([frame] * 3, axis=-1)
    tensor = transforms.Compose([
        transforms.ToTensor(),
        transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225]),
    ])(Image.fromarray(rgb)).unsqueeze(0).to(device)
    with torch.no_grad():
        embedding = app.state.model(tensor, normalize=True).cpu().numpy().flatten().tolist()
    return {"embedding": embedding, "model_fingerprint": app.state.model_fingerprint}
